package nl.hackyourfuture.dojoserver.mentorship.checkin.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import nl.hackyourfuture.dojoserver.mentorship.checkin.MentorshipCheckin;

import java.time.LocalDate;

@Schema(description = "A check-in of a mentorship as returned by the API")
public record MentorshipCheckinResponse(
        @Schema(
                description = "Unique identifier of the check-in, generated by the server",
                example = "mY3dQw9LrK",
                requiredMode = Schema.RequiredMode.REQUIRED
        )
        String id,

        @Schema(
                description = "The date of the check-in",
                example = "2026-05-20",
                requiredMode = Schema.RequiredMode.REQUIRED
        )
        LocalDate date,

        @Schema(
                description = "What was discussed or agreed at this check-in",
                example = "Discussed the final project plan.",
                requiredMode = Schema.RequiredMode.REQUIRED
        )
        String notes
) {
    public static MentorshipCheckinResponse from(MentorshipCheckin checkin) {
        return new MentorshipCheckinResponse(checkin.getId(), checkin.getDate(), checkin.getNotes());
    }
}
