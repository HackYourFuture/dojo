package nl.hackyourfuture.dojoserver.volunteer.assignment.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import nl.hackyourfuture.dojoserver.volunteer.VolunteerAssignmentType;
import nl.hackyourfuture.dojoserver.volunteer.assignment.VolunteerAssignment;

import java.time.LocalDate;

@Schema(description = "An assignment of a volunteer as returned by the API")
public record VolunteerAssignmentResponse(
        @Schema(
                description = "Unique identifier of the assignment, generated by the server",
                example = "aR3kWm9TqZ",
                requiredMode = Schema.RequiredMode.REQUIRED
        )
        String id,

        @Schema(
                description = "The type of the assignment",
                example = "TECH_MENTORSHIP",
                requiredMode = Schema.RequiredMode.REQUIRED
        )
        VolunteerAssignmentType type,

        @Schema(
                description = "The estimated total hours the volunteer spends on the assignment",
                example = "40",
                requiredMode = Schema.RequiredMode.REQUIRED,
                nullable = true
        )
        Integer estimatedHours,

        @Schema(
                description = "The date the assignment started",
                example = "2026-03-01",
                requiredMode = Schema.RequiredMode.REQUIRED
        )
        LocalDate startDate,

        @Schema(
                description = "The date the assignment ended. Empty while the assignment is ongoing.",
                example = "2026-06-30",
                requiredMode = Schema.RequiredMode.REQUIRED,
                nullable = true
        )
        LocalDate endDate,

        @Schema(
                description = "Free-form notes about this assignment",
                example = "Mentored two trainees through the final project.",
                requiredMode = Schema.RequiredMode.REQUIRED,
                nullable = true
        )
        String notes
) {
    public static VolunteerAssignmentResponse from(VolunteerAssignment assignment) {
        return new VolunteerAssignmentResponse(
                assignment.getId(),
                assignment.getType(),
                assignment.getEstimatedHours(),
                assignment.getStartDate(),
                assignment.getEndDate(),
                assignment.getNotes());
    }
}
