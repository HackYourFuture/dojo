package nl.hackyourfuture.dojoserver.volunteer.pairing.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import nl.hackyourfuture.dojoserver.trainee.profile.dto.TraineeReferenceResponse;
import nl.hackyourfuture.dojoserver.volunteer.pairing.MentorPairing;
import nl.hackyourfuture.dojoserver.volunteer.pairing.MentorPairingType;

import java.time.LocalDate;
import java.time.temporal.ChronoUnit;

@Schema(description = "A mentor pairing of a volunteer as returned by the API")
public record MentorPairingResponse(
        @Schema(
                description = "Unique identifier of the pairing, generated by the server",
                example = "pK4nW8sLqT",
                requiredMode = Schema.RequiredMode.REQUIRED
        )
        String id,

        @Schema(
                description = "The trainee the volunteer mentors",
                requiredMode = Schema.RequiredMode.REQUIRED
        )
        TraineeReferenceResponse trainee,

        @Schema(
                description = "What the volunteer mentors the trainee in",
                example = "ENGLISH_MENTORSHIP",
                requiredMode = Schema.RequiredMode.REQUIRED
        )
        MentorPairingType type,

        @Schema(
                description = "The date the pairing started",
                example = "2026-03-01",
                requiredMode = Schema.RequiredMode.REQUIRED
        )
        LocalDate startDate,

        @Schema(
                description = "The date of the last check-in with the trainee.",
                example = "2026-05-20",
                requiredMode = Schema.RequiredMode.REQUIRED,
                nullable = true
        )
        LocalDate lastCheckinDate,

        @Schema(
                description = "The date the pairing ended.",
                example = "2026-06-30",
                requiredMode = Schema.RequiredMode.REQUIRED,
                nullable = true
        )
        LocalDate endDate,

        @Schema(
                description = "The date of the next planned check-in with the trainee",
                example = "2026-06-17",
                requiredMode = Schema.RequiredMode.REQUIRED,
                nullable = true
        )
        LocalDate nextCheckinDate,

        @Schema(
                description = "Days from the last check-in until today.",
                example = "14",
                requiredMode = Schema.RequiredMode.REQUIRED,
                nullable = true
        )
        Integer daysSinceLastCheckin
) {
    public static MentorPairingResponse from(MentorPairing pairing) {
        return new MentorPairingResponse(
                pairing.getId(),
                TraineeReferenceResponse.from(pairing.getTrainee()),
                pairing.getType(),
                pairing.getStartDate(),
                pairing.getLastCheckinDate(),
                pairing.getEndDate(),
                pairing.getNextCheckinDate(),
                daysSince(pairing.getLastCheckinDate()));
    }

    // Worked out on every read rather than stored, so it never goes stale.
    private static Integer daysSince(LocalDate date) {
        if (date == null) {
            return null;
        }
        return (int) ChronoUnit.DAYS.between(date, LocalDate.now());
    }
}
